def search_kbk(query: str) -> list:
    """Search KBK codes by substring in code, short_name, or description (case-insensitive)."""
    query_lower = query.lower()
    results = []
    for entry in KBK_CODES:
        if (
            query_lower in entry["code"].lower()
            or query_lower in entry["short_name"].lower()
            or query_lower in entry["description"].lower()
        ):
            results.append(entry)
    return results


