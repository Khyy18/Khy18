# Salary calculation formulas
SALARY_KNOWLEDGE = """
Формула расчёта зарплаты:
1. Начислено = Оклад * Ставка * (1 + Надбавка_за_стаж/100 + Надбавка_за_категорию/100)
2. НДФЛ = Начислено * 0.13
3. На руки = Начислено - НДФЛ
4. Взносы ПФР = Начислено * 0.22
5. Взносы ОМС = Начислено * 0.051
6. Взносы ФСС = Начислено * 0.029
7. Взносы ФСС НС = Начислено * 0.002
"""

# Vacation calculation
VACATION_KNOWLEDGE = """
Формула расчёта отпускных:
1. Среднедневной заработок = Общий доход за 12 месяцев / 12 / 29.3
2. Отпускные (начислено) = Среднедневной заработок * Количество дней отпуска
3. НДФЛ с отпускных = Начислено * 0.13
4. На руки = Начислено - НДФЛ
Примечание: 29.3 - среднее число дней в месяце по ТК РФ.
"""

# Sick leave calculation
SICK_KNOWLEDGE = """
Формула расчёта больничного листа:
1. Определить процент оплаты по стажу:
   - Стаж < 5 лет: 60%
   - Стаж 5-8 лет: 80%
   - Стаж > 8 лет: 100%
2. Среднедневной заработок = Доход за 2 года / 730
3. Дневное пособие = Среднедневной заработок * Процент по стажу
4. Начислено = Дневное пособие * Количество дней больничного
5. НДФЛ = Начислено * 0.13
6. На руки = Начислено - НДФЛ
"""

